/** Rapatkan polyline jadi titik-titik berjarak ± `step` (untuk deteksi progres tracing). */
export function rapatkan(goresan: Goresan, step = 4): Goresan {
  const out: Goresan = [];
  for (let i = 0; i < goresan.length - 1; i++) {
    const [x1, y1] = goresan[i];
    const [x2, y2] = goresan[i + 1];
    const jarak = Math.hypot(x2 - x1, y2 - y1);
    const n = Math.max(1, Math.round(jarak / step));
    for (let k = 0; k < n; k++) out.push([x1 + ((x2 - x1) * k) / n, y1 + ((y2 - y1) * k) / n]);
  }
  out.push(goresan[goresan.length - 1]);
  return out;
}
