// Kurva dihasilkan dari sampel busur elips (bukan hand-plot) agar mulus & mudah dirawat.
export type Titik = [number, number];
export type Goresan = Titik[];

// Busur elips tersampel. Sudut derajat; 0=kanan, 90=BAWAH (layar y ke bawah, positif = searah jarum jam).
// a1 < a0 berarti menyapu berlawanan arah jarum jam.
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n = 14): Goresan {
  const pts: Goresan = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    pts.push([Math.round((cx + rx * Math.cos(a)) * 10) / 10, Math.round((cy + ry * Math.sin(a)) * 10) / 10]);
  }
  return pts;
}
